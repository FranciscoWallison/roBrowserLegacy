/**
 * tools/gen-warp-graph.mjs
 *
 * Offline generator for the FULL static-warp graph consumed by the
 * SeamlessFieldFlight plugin's "all portals" mode. Parses every rAthena warp
 * NPC (the walk-into portals) and emits src/Plugins/SeamlessFieldFlight/WarpGraph.js.
 *
 * Grammar (TAB/space separated):
 *   <srcMap>,<x>,<y>,<dir>   warp   <name>   <xs>,<ys>,<dstMap>,<toX>,<toY>
 *
 * Output (compact, keyed by source map; one entry per warp tile):
 *   { "prt_fild08": [ [x, y, "dstMap", toX, toY], ... ], ... }
 *
 * Only covers STATIC warp NPCs (script `warp "map",x,y;` commands and instant
 * teleports — kafra/@warp/save — are not portals you walk into, so they are not
 * preloadable and fall back to the normal loading screen).
 *
 * Run: node roBrowserLegacy/tools/gen-warp-graph.mjs
 */

import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, resolve, join } from 'path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(__dirname, '..', '..'); // emulator/ragnarok

// Scan the renewal NPC tree + the shared warps tree. Skip pre-re (renewal server).
const SCAN_DIRS = [
	join(REPO, 'rathena', 'npc', 're'),
	join(REPO, 'rathena', 'npc', 'warps')
];

const OUTPUT = resolve(__dirname, '..', 'src', 'Plugins', 'SeamlessFieldFlight', 'WarpGraph.js');
const MAP_INDEX = join(REPO, 'rathena', 'db', 'map_index.txt');

function loadValidMaps() {
	const set = new Set();
	if (!existsSync(MAP_INDEX)) {
		return null;
	}
	for (const line of readFileSync(MAP_INDEX, 'utf8').split(/\r?\n/)) {
		const t = line.trim();
		if (!t || t.startsWith('//')) continue;
		const m = t.match(/^([A-Za-z0-9_@#-]+)/);
		if (m) set.add(m[1].toLowerCase());
	}
	return set.size ? set : null;
}

/** Recursively collect .txt files under a directory. */
function collectTxt(dir, out) {
	let entries;
	try {
		entries = readdirSync(dir);
	} catch (e) {
		return;
	}
	for (const name of entries) {
		const full = join(dir, name);
		let st;
		try {
			st = statSync(full);
		} catch (e) {
			continue;
		}
		if (st.isDirectory()) {
			collectTxt(full, out);
		} else if (name.toLowerCase().endsWith('.txt')) {
			out.push(full);
		}
	}
}

function parseWarp(line) {
	const trimmed = line.trim();
	if (!trimmed || trimmed.startsWith('//')) return null;

	const parts = trimmed.split(/[\t ]+/);
	if (parts.length < 4) return null;
	if (!/^warp2?$/i.test(parts[1])) return null;

	const src = parts[0].split(',');
	const dst = parts[3].split(',');
	if (src.length < 3 || dst.length < 5) return null;

	const srcMap = src[0].toLowerCase();
	const sx = parseInt(src[1], 10);
	const sy = parseInt(src[2], 10);
	const dstMap = dst[2].toLowerCase();
	const tox = parseInt(dst[3], 10);
	const toy = parseInt(dst[4], 10);

	if ([sx, sy, tox, toy].some(Number.isNaN)) return null;
	if (srcMap === dstMap) return null;

	return { srcMap, sx, sy, dstMap, tox, toy };
}

function main() {
	const valid = loadValidMaps();
	const files = [];
	for (const dir of SCAN_DIRS) {
		collectTxt(dir, files);
	}
	if (!files.length) {
		console.error('No .txt files found under:', SCAN_DIRS.join(', '));
		process.exit(1);
	}

	const graph = {};
	const seen = new Set(); // dedupe identical warp tiles
	let scanned = 0;
	let kept = 0;

	for (const file of files) {
		let content;
		try {
			content = readFileSync(file, 'utf8');
		} catch (e) {
			continue;
		}
		for (const line of content.split(/\r?\n/)) {
			const w = parseWarp(line);
			if (!w) continue;
			scanned++;

			if (valid && (!valid.has(w.srcMap) || !valid.has(w.dstMap))) continue;

			const key = `${w.srcMap}|${w.sx}|${w.sy}|${w.dstMap}`;
			if (seen.has(key)) continue;
			seen.add(key);

			(graph[w.srcMap] || (graph[w.srcMap] = [])).push([w.sx, w.sy, w.dstMap, w.tox, w.toy]);
			kept++;
		}
	}

	// Sort keys for stable output.
	const out = {};
	for (const k of Object.keys(graph).sort()) {
		out[k] = graph[k];
	}

	const banner =
		'/**\n' +
		' * Plugins/SeamlessFieldFlight/WarpGraph.js\n' +
		' *\n' +
		' * AUTO-GENERATED by tools/gen-warp-graph.mjs — do not edit by hand.\n' +
		' * Full static-warp graph from rAthena. Keyed by source map; each warp tile\n' +
		' * is [x, y, dstMap, toX, toY]. Used to preload the destination of the\n' +
		' * portal the player is walking toward.\n' +
		' */\n\n';

	// Compact JSON (no pretty indentation) to keep the file small.
	const body = 'const WarpGraph = ' + JSON.stringify(out) + ';\n\nexport default WarpGraph;\n';

	writeFileSync(OUTPUT, banner + body, 'utf8');

	const bytes = Buffer.byteLength(banner + body, 'utf8');
	console.log(`Scanned ${scanned} warps across ${files.length} files.`);
	console.log(`Source maps: ${Object.keys(out).length}, unique warp tiles: ${kept}.`);
	console.log(`Wrote ${OUTPUT} (${(bytes / 1024).toFixed(0)} KB)`);
}

main();
